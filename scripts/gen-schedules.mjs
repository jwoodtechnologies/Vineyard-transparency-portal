#!/usr/bin/env node
/**
 * Writes worker/lib/schedules.generated.ts from the real schedule settings: the Worker's cron triggers in
 * wrangler.jsonc and the schedule blocks of .github/workflows/*.yml (worker/lib/scheduleSources.ts reads
 * them). Run after changing any of those; tests/schedules.test.ts fails when the file is out of date.
 *
 *   node scripts/gen-schedules.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { wranglerCrons, workflowSchedule } from '../worker/lib/scheduleSources.ts';

const root = new URL('..', import.meta.url).pathname;
const worker = wranglerCrons(readFileSync(join(root, 'wrangler.jsonc'), 'utf8'));
const dir = join(root, '.github/workflows');
const workflows = readdirSync(dir)
  .filter((f) => /\.ya?ml$/.test(f))
  .sort()
  .map((f) => workflowSchedule(f, readFileSync(join(dir, f), 'utf8')))
  .filter(Boolean);
const body = `/** Generated by scripts/gen-schedules.mjs from wrangler.jsonc and .github/workflows. Do not edit by hand. */
import type { WorkflowSchedule } from './scheduleSources';

export const WORKER_CRONS: string[] = ${JSON.stringify(worker)};

export const WORKFLOW_SCHEDULES: WorkflowSchedule[] = ${JSON.stringify(workflows, null, 2)};
`;
writeFileSync(join(root, 'worker/lib/schedules.generated.ts'), body);
console.log(`worker crons: ${worker.length}, workflows with schedules: ${workflows.length}`);
